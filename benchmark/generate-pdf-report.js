const fs = require('fs');
const puppeteer = require('puppeteer');

async function generatePDFReport() {
  // Read analysis data
  const analysis = JSON.parse(fs.readFileSync('benchmark/analysis.json'));
  
  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <title>Food Delivery Performance Report</title>
      <style>
        body { font-family: Arial, sans-serif; margin: 40px; line-height: 1.6; }
        .header { text-align: center; border-bottom: 2px solid #333; padding-bottom: 20px; }
        .metric { background: #f8f9fa; padding: 20px; margin: 20px 0; border-radius: 8px; }
        .success { border-left: 4px solid #28a745; }
        .warning { border-left: 4px solid #ffc107; }
        .danger { border-left: 4px solid #dc3545; }
        .stats { display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 20px; }
        .stat { text-align: center; padding: 15px; background: white; border-radius: 5px; }
        table { width: 100%; border-collapse: collapse; margin: 20px 0; }
        th, td { padding: 12px; text-align: left; border-bottom: 1px solid #ddd; }
        .footer { margin-top: 40px; padding-top: 20px; border-top: 1px solid #ccc; font-size: 0.9em; color: #666; }
      </style>
    </head>
    <body>
      <div class="header">
        <h1>🚀 Food Delivery Platform</h1>
        <h2>Performance Benchmark Report</h2>
        <p>Generated on: ${new Date().toLocaleString()}</p>
      </div>

      <div class="metric success">
        <h3>📊 Executive Summary</h3>
        <div class="stats">
          <div class="stat">
            <h4>${analysis.summary.totalRequests.toLocaleString()}</h4>
            <small>Total Requests</small>
          </div>
          <div class="stat">
            <h4>${analysis.summary.successRate}%</h4>
            <small>Success Rate</small>
          </div>
          <div class="stat">
            <h4>${analysis.summary.p95ResponseTime}ms</h4>
            <small>95th Percentile</small>
          </div>
          <div class="stat">
            <h4>${analysis.summary.requestRate}</h4>
            <small>Requests/sec</small>
          </div>
        </div>
      </div>

      <div class="metric">
        <h3>⏱️ Response Time Analysis</h3>
        <table>
          <tr><th>Metric</th><th>Value</th></tr>
          <tr><td>Average Response Time</td><td>${analysis.summary.avgResponseTime}ms</td></tr>
          <tr><td>95th Percentile</td><td>${analysis.summary.p95ResponseTime}ms</td></tr>
          <tr><td>Request Rate</td><td>${analysis.summary.requestRate} RPS</td></tr>
        </table>
      </div>

      <div class="metric">
        <h3>🎯 Performance Assessment</h3>
        <table>
          <tr><th>Category</th><th>Rating</th><th>Status</th></tr>
          <tr><td>Response Time</td><td>${analysis.assessment.responseTime}</td><td class="${getStatusClass(analysis.assessment.responseTime)}">${getStatusIcon(analysis.assessment.responseTime)}</td></tr>
          <tr><td>Throughput</td><td>${analysis.assessment.throughput}</td><td class="${getStatusClass(analysis.assessment.throughput)}">${getStatusIcon(analysis.assessment.throughput)}</td></tr>
          <tr><td>Reliability</td><td>${analysis.assessment.reliability}</td><td class="${getStatusClass(analysis.assessment.reliability)}">${getStatusIcon(analysis.assessment.reliability)}</td></tr>
        </table>
      </div>

      <div class="metric">
        <h3>🚨 Error Analysis</h3>
        <table>
          <tr><th>Error Type</th><th>Count</th><th>Percentage</th></tr>
          ${Object.entries(analysis.errors).filter(([, count]) => count > 0).map(([error, count]) => 
            `<tr><td>${error}</td><td>${count}</td><td>${((count/analysis.summary.totalRequests)*100).toFixed(1)}%</td></tr>`
          ).join('')}
        </table>
      </div>

      <div class="footer">
        <p><strong>Generated by:</strong> Food Delivery Platform Benchmark Suite</p>
        <p><strong>Test Configuration:</strong> Artillery Load Test with Kong API Gateway</p>
        <p><strong>Services Tested:</strong> Auth, Restaurant, Order, Payment, Delivery, Tracking</p>
      </div>
    </body>
    </html>
  `;

  // Generate PDF
  const browser = await puppeteer.launch();
  const page = await browser.newPage();
  await page.setContent(html);
  await page.pdf({ 
    path: 'benchmark/performance-report.pdf', 
    format: 'A4',
    margin: { top: '20px', right: '20px', bottom: '20px', left: '20px' }
  });
  await browser.close();
  
  console.log('✅ PDF Performance Report Generated: benchmark/performance-report.pdf');
}

function getStatusClass(rating) {
  return rating === 'EXCELLENT' ? 'success' : rating === 'GOOD' || rating === 'ACCEPTABLE' ? 'warning' : 'danger';
}

function getStatusIcon(rating) {
  return rating === 'EXCELLENT' ? '✅' : rating === 'GOOD' || rating === 'ACCEPTABLE' ? '⚠️' : '❌';
}

generatePDFReport().catch(console.error);
